#include "push_swap.h"

void    pa(t_list **a, t_list **b)
{
    t_list  *tmp;

    if (!b || !*b)
        return ;
    tmp = *b;
    *b = (*b)->next;
    tmp->next = *a;
    *a = tmp;
    ft_putendl_fd("pa", 1);
}