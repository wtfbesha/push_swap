# include "push_swap.h"

void    pb(t_list **a, t_list **b)
{
    t_list  *tmp;

    if (!a || !*a)
        return ;
    tmp = *a;
    *a = (*a)->next;
    tmp->next = *b;
    *b = tmp;
    ft_putendl_fd("pb", 1);
}